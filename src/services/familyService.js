/**
 * الاشتراك في تحديثات العائلات في الوقت الفعلي
 * @param {Function} callback - دالة الاستدعاء الراجع التي تستقبل المصفوفة المحدثة
 * @returns {Function} دالة إلغاء الاشتراك (unsubscribe)
 */
export const subscribeFamilies = (callback) => {
  if (isDemoMode) {
    initLocalStorage();
    demoSubscribers.add(callback);
    // استدعاء فوري بالبيانات الحالية
    callback(getDemoFamilies());
    return () => {
      demoSubscribers.delete(callback);
    };
  } else {
    const q = query(collection(db, "families"), orderBy("createdAt", "asc"));
    return onSnapshot(q, (snapshot) => {
      const families = snapshot.docs.map(doc => ({
        id: doc.id,
        ...doc.data(),
        // تحويل Timestamp الخاص بفايرستور إلى صيغة ISO النصية لتوحيد الواجهات
        createdAt: doc.data().createdAt?.toDate ? doc.data().createdAt.toDate().toISOString() : new Date().toISOString()
      }));
      callback(families);
    }, (error) => {
      console.error("Firestore listening error, falling back to Local Storage:", error);
      // Fallback in case of permissions error
      initLocalStorage();
      demoSubscribers.add(callback);
      callback(getDemoFamilies());
    });
  }
};

/**
 * إضافة عائلة جديدة
 * @param {Object} familyData - بيانات العائلة
 */
export const addFamily = async (familyData) => {
  const newFamily = {
    name: familyData.name.trim(),
    idNumber: familyData.idNumber.trim(),
    phone: familyData.phone.trim(),
    membersCount: parseInt(familyData.membersCount) || 1,
    location: familyData.location.trim(),
    status: familyData.status ? familyData.status.trim() : "أعزب",
    dob: familyData.dob ? familyData.dob.trim() : "",
    wifeName: familyData.wifeName ? familyData.wifeName.trim() : "",
    wifeId: familyData.wifeId ? familyData.wifeId.trim() : "",
    wifeDob: familyData.wifeDob ? familyData.wifeDob.trim() : "",
    notes: familyData.notes ? familyData.notes.trim() : "",
    createdAt: new Date().toISOString()
  };

  if (isDemoMode) {
    const families = getDemoFamilies();
    const id = "demo-" + Date.now();
    families.push({ id, ...newFamily });
    localStorage.setItem("kareem_camp_families_v4", JSON.stringify(families));
    notifyDemoSubscribers();
    return id;
  } else {
    const docRef = await addDoc(collection(db, "families"), {
      ...newFamily,
      createdAt: new Date() // Firestore Server Timestamp support
    });
    return docRef.id;
  }
};

/**
 * تعديل بيانات عائلة موجودة
 * @param {string} id - معرف العائلة
 * @param {Object} familyData - البيانات الجديدة
 */
export const updateFamily = async (id, familyData) => {
  const updatedData = {
    name: familyData.name.trim(),
    idNumber: familyData.idNumber.trim(),
    phone: familyData.phone.trim(),
    membersCount: parseInt(familyData.membersCount) || 1,
    location: familyData.location.trim(),
    status: familyData.status ? familyData.status.trim() : "أعزب",
    dob: familyData.dob ? familyData.dob.trim() : "",
    wifeName: familyData.wifeName ? familyData.wifeName.trim() : "",
    wifeId: familyData.wifeId ? familyData.wifeId.trim() : "",
    wifeDob: familyData.wifeDob ? familyData.wifeDob.trim() : "",
    notes: familyData.notes ? familyData.notes.trim() : ""
  };

  if (isDemoMode) {
    const families = getDemoFamilies();
    const index = families.findIndex(f => f.id === id);
    if (index !== -1) {
      families[index] = { ...families[index], ...updatedData };
      localStorage.setItem("kareem_camp_families_v4", JSON.stringify(families));
      notifyDemoSubscribers();
    }
  } else {
    const docRef = doc(db, "families", id);
    await updateDoc(docRef, updatedData);
  }
};

/**
 * حذف سجل عائلة
 * @param {string} id - معرف العائلة
 */
export const deleteFamily = async (id) => {
  if (isDemoMode) {
    let families = getDemoFamilies();
    families = families.filter(f => f.id !== id);
    localStorage.setItem("kareem_camp_families_v4", JSON.stringify(families));
    notifyDemoSubscribers();
  } else {
    const docRef = doc(db, "families", id);
    await deleteDoc(docRef);
  }
};

