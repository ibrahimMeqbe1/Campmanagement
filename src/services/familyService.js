// المشتركون في التغييرات للوضع التجريبي (نظام Publish/Subscribe بسيط)
const demoSubscribers = new Set();

const notifyDemoSubscribers = () => {
  const families = getDemoFamilies();
  demoSubscribers.forEach(cb => cb(families));
};

const getDemoFamilies = () => {
  initLocalStorage();
  const data = JSON.parse(localStorage.getItem("kareem_camp_families_v4") || "[]");
  // فرز تصاعدي حسب تاريخ الإنشاء (الجديد في آخر الكشف)
  return data.sort((a, b) => new Date(a.createdAt) - new Date(b.createdAt));
};

